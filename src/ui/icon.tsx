export type IconName = keyof typeof ICONS;

/** Renders a data-named icon. Size it with a `size-*` class. */
export function Icon({ name, ...props }: LucideProps & { name: IconName }) {
  const C = ICONS[name];
  return <C aria-hidden="true" {...props} />;
}
